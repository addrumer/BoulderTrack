package com.example.bouldertrack.domain.model

/**
 * Dostępne tryby motywu graficznego aplikacji.
 */
enum class AppThemeMode {
    /** Automatyczne dopasowanie do ustawień systemowych urządzenia. */
    SYSTEM,
    /** Jasny motyw graficzny. */
    LIGHT,
    /** Ciemny motyw grafitowy z pomarańczowymi akcentami. */
    DARK,
    /** Głęboka, czysta czerń (AMOLED) oszczędzająca baterię na ekranach OLED. */
    AMOLED
}
